// Generates internal/purify/tags.go and internal/purify/attrs.go from the
// copy of DOMPurify that the mermaid build bundles. The lists are read from
// the bundle, not from node_modules/dompurify, because npm can resolve a
// newer DOMPurify than the one that mermaid ships.
//
// Usage: node gen-purify-lists.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CHUNK = path.join(HERE, 'node_modules/mermaid/dist/chunks/mermaid.esm/chunk-DLUCIBNR.mjs');
const OUT = path.join(HERE, '../../internal/purify');

const src = fs.readFileSync(CHUNK, 'utf8');
const version = /DOMPurify\.version = "([^"]+)"/.exec(src)[1];

function list(name) {
  const re = new RegExp('^var ' + name.replace('$', '\\$') + ' = freeze\\((\\[.*\\])\\);$', 'm');
  const m = re.exec(src);
  if (!m) {
    throw new Error('list not found: ' + name);
  }
  return JSON.parse(m[1]);
}

function goList(name, doc, values) {
  let out = `// ${doc}\nvar ${name} = []string{\n`;
  let line = '\t';
  for (const v of values) {
    const item = JSON.stringify(v) + ', ';
    if (line.length + item.length > 100) {
      out += line.trimEnd() + '\n';
      line = '\t';
    }
    line += item;
  }
  out += line.trimEnd() + '\n}\n';
  return out;
}

const header = (file) =>
  `// Code generated by tools/reference/gen-purify-lists.mjs. DO NOT EDIT.\n\n` +
  `// Ported from dompurify ${version}, src/${file}.\n\npackage purify\n\n`;

const tags =
  header('tags.ts') +
  [
    goList('htmlTags', 'htmlTags is the list html of tags.ts.', list('html$1')),
    goList('svgTags', 'svgTags is the list svg of tags.ts.', list('svg$1')),
    goList('svgFilterTags', 'svgFilterTags is the list svgFilters of tags.ts.', list('svgFilters')),
    goList(
      'svgDisallowedTags',
      'svgDisallowedTags is the list svgDisallowed of tags.ts. It is used only\n// for the namespace check.',
      list('svgDisallowed')
    ),
    goList('mathMLTags', 'mathMLTags is the list mathMl of tags.ts.', list('mathMl$1')),
    goList(
      'mathMLDisallowedTags',
      'mathMLDisallowedTags is the list mathMlDisallowed of tags.ts.',
      list('mathMlDisallowed')
    ),
    goList('textTags', 'textTags is the list text of tags.ts.', list('text')),
  ].join('\n');

const attrs =
  header('attrs.ts') +
  [
    goList('htmlAttrs', 'htmlAttrs is the list html of attrs.ts.', list('html')),
    goList('svgAttrs', 'svgAttrs is the list svg of attrs.ts.', list('svg')),
    goList('mathMLAttrs', 'mathMLAttrs is the list mathMl of attrs.ts.', list('mathMl')),
    goList('xmlAttrs', 'xmlAttrs is the list xml of attrs.ts.', list('xml')),
  ].join('\n');

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'tags.go'), tags);
fs.writeFileSync(path.join(OUT, 'attrs.go'), attrs);
console.log(`dompurify ${version}: wrote tags.go and attrs.go`);
