// Generates the collation table and the golden data of js.LocaleCompare
// (internal/js/str_swimlanes.go) from the ICU collator of Chromium.
//
//   node gen-js-localecompare.mjs
//
// It runs probes/locale-compare.js in the reference browser (oracle.mjs eval)
// and writes
//
//   internal/js/str_swimlanes_table.go         the weights of U+0000..U+07FF
//   internal/js/testdata/localecompare.json.gz pairs of strings with the
//                                              result of localeCompare and
//                                              of the table model
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mmdg-collate-'));
const argsFile = path.join(tmp, 'args.json');
const outFile = path.join(tmp, 'out.json');
fs.writeFileSync(argsFile, JSON.stringify({ max: 0x800, seed: 0x6d6d6467, pairs: 4000 }));
execFileSync(
  'node',
  ['oracle.mjs', 'eval', 'probes/locale-compare.js', '--bare', '--args', argsFile, '--out', outFile],
  { cwd: here, stdio: 'inherit' }
);
const result = JSON.parse(fs.readFileSync(outFile, 'utf8'));
fs.rmSync(tmp, { recursive: true, force: true });

for (const set of result.sets) {
  console.error(`${set.name}: the model agrees with ICU for ${set.agree} of ${set.total} pairs`);
  if (set.exact && set.agree !== set.total) {
    throw new Error(`the model is not exact for the set ${set.name}`);
  }
}

let maxS = 0;
let maxT = 0;
let maxP = 0;
for (let cp = 0; cp < result.max; cp++) {
  maxP = Math.max(maxP, result.P[cp]);
  maxS = Math.max(maxS, result.S[cp]);
  maxT = Math.max(maxT, result.T[cp]);
}
if (maxP > 0xffff || maxS > 0xff || maxT > 0xff) {
  throw new Error(`weights out of range: ${maxP} ${maxS} ${maxT}`);
}

let go = `// Code generated by tools/reference/gen-js-localecompare.mjs. DO NOT EDIT.

package js

// localeCompareMax is the first code point that the table does not cover.
const localeCompareMax = 0x${result.max.toString(16)}

// localeCompareTable has the collation weights of the code points below
// localeCompareMax, from the ICU collator of Chromium with the locale en-US:
// the primary rank in the bits 16 to 31, the secondary rank in the bits 8 to
// 15 and the tertiary rank in the bits 0 to 7. A primary rank of 0 says
// that the collator ignores the code point.
var localeCompareTable = [localeCompareMax]uint32{
`;
for (let cp = 0; cp < result.max; cp += 8) {
  const row = [];
  for (let i = cp; i < cp + 8 && i < result.max; i++) {
    const v = ((result.P[i] << 16) | (result.S[i] << 8) | result.T[i]) >>> 0;
    row.push('0x' + v.toString(16).padStart(8, '0'));
  }
  go += '\t' + row.join(', ') + `, // U+${cp.toString(16).toUpperCase().padStart(4, '0')}\n`;
}
go += '}\n';
fs.writeFileSync(path.join(root, 'internal/js/str_swimlanes_table.go'), go);

const golden = {
  sets: result.sets.map((set) => ({
    name: set.name,
    exact: set.exact,
    agree: set.agree,
    // [a, b, the sign of a.localeCompare(b), the result of the model]
    pairs: set.pairs,
  })),
};
const goldenFile = path.join(root, 'internal/js/testdata/localecompare.json.gz');
fs.writeFileSync(goldenFile, zlib.gzipSync(JSON.stringify(golden), { level: 9 }));
console.error(`wrote ${goldenFile} (${fs.statSync(goldenFile).size} bytes)`);
