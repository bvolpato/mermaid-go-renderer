// Writes internal/parity/images_gen.go: the natural sizes of the images
// that the fixtures of the corpus name by URL.
//
// A label or an image shape can name an image by URL. The reference
// renderer ran in a page with access to the network, so Chromium loaded
// those images, and the reference output has their sizes. The Go renderer
// never reads from the network: a caller gives it the natural size of each
// image (render.Options.ImageSize). This script records the sizes that
// Chromium sees, so that the parity command and the tests can give them.
//
// The script finds the http and https URLs of images in the fixtures
// (the src of an img element and the img of an image shape), loads each one
// in the page of the browser oracle and reads naturalWidth and
// naturalHeight. A URL that does not load is not in the table: the renderer
// then treats it as a failed image, as Chromium does. It needs the network.
//
// Usage (in tools/reference): node gen-corpus-images.mjs
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
// Every corpus: the end-to-end fixtures and the documentation examples.
const corpus = path.join(repoRoot, 'testdata/corpus');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      walk(p, out);
    } else if (e.name.endsWith('.mmd')) {
      out.push(p);
    }
  }
  return out;
}
const urls = new Set();
for (const file of walk(corpus)) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/(?:src\s*=|img\s*:)\s*['"]?(https?:\/\/[^'"\s>)]+)/g)) {
    urls.add(m[1]);
  }
}
const list = [...urls].sort();

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mmdg-images-'));
const script = path.join(tmp, 'natural.js');
const argsFile = path.join(tmp, 'args.json');
const outFile = path.join(tmp, 'out.json');
fs.writeFileSync(
  script,
  `const out = [];
for (const src of args.urls) {
  const img = new Image();
  const event = await new Promise((res) => {
    img.addEventListener('load', () => res('load'));
    img.addEventListener('error', () => res('error'));
    setTimeout(() => res('timeout'), 30000);
    img.src = src;
  });
  out.push({ src, event, width: img.naturalWidth, height: img.naturalHeight });
}
return out;
`
);
fs.writeFileSync(argsFile, JSON.stringify({ urls: list }));
execFileSync(process.execPath, [path.join(here, 'oracle.mjs'), 'eval', script, '--args', argsFile, '--out', outFile], { stdio: 'inherit' });
const results = JSON.parse(fs.readFileSync(outFile, 'utf8'));
fs.rmSync(tmp, { recursive: true, force: true });

const rows = results
  .filter((r) => r.event === 'load')
  .map((r) => `\t${JSON.stringify(r.src)}: {${r.width}, ${r.height}},`)
  .join('\n');
const go = `// Code generated by tools/reference/gen-corpus-images.mjs. DO NOT EDIT.

package parity

// CorpusImages has the natural size (naturalWidth and naturalHeight in
// Chromium) of each image that a fixture of the corpus names by URL. The
// reference renderer loaded these images from the network. A URL of the
// corpus that is not here did not load.
var CorpusImages = map[string][2]float64{
${rows}
}
`;
const goFile = path.join(repoRoot, 'internal/parity/images_gen.go');
fs.writeFileSync(goFile, go);
// The file must be in gofmt form.
execFileSync('gofmt', ['-w', goFile]);
for (const r of results) {
  console.error(`${r.event} ${r.width} x ${r.height} ${r.src}`);
}
