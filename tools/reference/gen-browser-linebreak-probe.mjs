// Writes internal/browser/testdata/linebreak-ascii.json and
// internal/browser/linebreak_ascii_gen.go: the places where Chromium can
// break a line between two printable ASCII characters.
//
// Blink does not use the Unicode line breaking algorithm for a pair of
// ASCII characters. It has a table (kAsciiLineBreakTable in
// platform/text/text_break_iterator.cc) that is compatible with other
// browsers: for example a line can break after a hyphen and after a
// question mark, and before an opening bracket after some characters. So
// "[DBServer\SharedDbInstance].[SupportDb]" breaks before the second
// bracket, and "a.b" does not break.
//
// The script asks Chromium. For each pair of characters from "!" to "~" it
// lays out the two characters in a block that is 1px wide. The block has
// two lines when a line can break between them. It also lays out a digit
// after a hyphen behind each character, because that break depends on the
// character before the hyphen (ShouldBreakAfter).
//
// The Go file has the table as data. The JSON file has the same answers as
// the golden data of TestLineBreakASCIIAgainstChromium.
//
// Usage (in tools/reference): node gen-browser-linebreak-probe.mjs
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../..');
const FIRST = 0x21;
const LAST = 0x7e;

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const svg = (inner) => `<svg id="my-svg" width="100%" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`;
const block = (text) => `<div class="t" style="width: 1px; font: 10px/10px arial; white-space: normal">${escape(text)}</div>`;
const fo = (blocks) => svg(`<foreignObject width="2000" height="20000"><div xmlns="http://www.w3.org/1999/xhtml">${blocks.join('')}</div></foreignObject>`);
const query = [{ sel: '.t', op: 'rect', all: true }];

const cases = [];
// One case for each first character: the pairs with every second character.
for (let a = FIRST; a <= LAST; a++) {
  const blocks = [];
  for (let b = FIRST; b <= LAST; b++) {
    blocks.push(block(String.fromCharCode(a, b)));
  }
  cases.push({ name: `pair-${a}`, html: fo(blocks), queries: query });
}
// A digit after a hyphen, behind each character and at the start.
{
  const blocks = [block('-1')];
  for (let a = FIRST; a <= LAST; a++) {
    blocks.push(block(String.fromCharCode(a) + '-1'));
  }
  cases.push({ name: 'hyphen-digit', html: fo(blocks), queries: query });
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mmdg-linebreak-'));
const casesFile = path.join(tmp, 'cases.json');
const resultsFile = path.join(tmp, 'results.json');
fs.writeFileSync(casesFile, JSON.stringify({ cases }));
execFileSync(
  process.execPath,
  [path.join(here, 'oracle.mjs'), 'eval', path.join(repoRoot, '.parity/probe/dom.js'), '--args', casesFile, '--out', resultsFile],
  { stdio: 'inherit' }
);
const results = JSON.parse(fs.readFileSync(resultsFile, 'utf8'));
fs.rmSync(tmp, { recursive: true, force: true });

// A block with one line is 10px high. More lines mean a break.
const lines = (rect) => Math.round(rect[3] / 10);
const rows = [];
for (let a = FIRST; a <= LAST; a++) {
  const rects = results[a - FIRST].results[0];
  rows.push(rects.map((r) => (lines(r) > 1 ? '1' : '0')).join(''));
}
// With a break between the character and the hyphen, the block has one line
// more than the break between the hyphen and the digit gives. The row of
// the pair table says whether a line can break before the hyphen.
const hyphenRects = results[results.length - 1].results[0];
const hyphenIndex = '-'.charCodeAt(0) - FIRST;
const hyphenStart = lines(hyphenRects[0]) > 1 ? '1' : '0';
let hyphenDigit = '';
for (let a = FIRST; a <= LAST; a++) {
  const before = rows[a - FIRST][hyphenIndex] === '1' ? 1 : 0;
  hyphenDigit += lines(hyphenRects[a - FIRST + 1]) - 1 - before > 0 ? '1' : '0';
}

const golden = { first: FIRST, last: LAST, rows, hyphenDigit, hyphenDigitAtStart: hyphenStart };
fs.writeFileSync(path.join(repoRoot, 'internal/browser/testdata/linebreak-ascii.json'), JSON.stringify(golden, null, 1) + '\n');

const goRows = rows.map((row, i) => `\t${JSON.stringify(row)}, // ${JSON.stringify(String.fromCharCode(FIRST + i))}`).join('\n');
const go = `// Code generated by tools/reference/gen-browser-linebreak-probe.mjs. DO NOT EDIT.

package browser

// asciiBreakFirst and asciiBreakLast are the first and the last character
// of asciiBreakTable.
const (
	asciiBreakFirst = ${FIRST}
	asciiBreakLast  = ${LAST}
)

// asciiBreakTable says where Chromium can break a line between two
// printable ASCII characters: the row is the character before the break,
// and the column is the character after it. A '1' is a break opportunity.
// The values are what Chromium does (kAsciiLineBreakTable in Blink).
var asciiBreakTable = [...]string{
${goRows}
}

// asciiBreakHyphenDigit says, for each character, whether a line can break
// between a hyphen and a digit when the character is before the hyphen.
const asciiBreakHyphenDigit = ${JSON.stringify(hyphenDigit)}
`;
fs.writeFileSync(path.join(repoRoot, 'internal/browser/linebreak_ascii_gen.go'), go);
const count = rows.reduce((n, row) => n + [...row].filter((c) => c === '1').length, 0);
console.error(`${rows.length} x ${rows[0].length} pairs, ${count} break opportunities, hyphen-digit ${hyphenDigit}`);
