// Generates internal/ru/shapedefs_gen.go from rendering-elements/shapes.ts:
// the documented shape definitions with their aliases, and the list of
// undocumented shapes. Run from tools/reference: node gen-shapedefs.mjs
import fs from 'node:fs';
const src = fs.readFileSync('../../.upstream/mermaid-12.2.0/packages/mermaid/src/rendering-util/rendering-elements/shapes.ts', 'utf8');
const defsText = src.slice(src.indexOf('export const shapesDefs = ['), src.indexOf('] as const satisfies ShapeDefinition[]'));
const defs = [];
for (const block of defsText.split(/\n  \{\n/).slice(1)) {
  const str = (key) => (block.match(new RegExp(`${key}: '((?:[^'\\\\]|\\\\.)*)'`)) || [])[1];
  const list = (key) => {
    const m = block.match(new RegExp(`${key}: \\[([^\\]]*)\\]`));
    return m ? [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]) : [];
  };
  const handler = (block.match(/handler: (\w+)/) || [])[1];
  if (!handler) throw new Error('no handler in block: ' + block.slice(0, 80));
  defs.push({ semanticName: str('semanticName'), name: str('name'), shortName: str('shortName'), aliases: list('aliases'), internalAliases: list('internalAliases'), handler });
}
const undocText = src.slice(src.indexOf('const undocumentedShapes = {'), src.indexOf('} as const;', src.indexOf('const undocumentedShapes = {')));
const undocumented = [...undocText.matchAll(/^\s{4}(\w+),/gm)].map((m) => m[1]);
// Map import names to the exported function names (import { a as b }).
const q = (s) => JSON.stringify(s);
let out = '// Code generated by tools/reference/gen-shapedefs.mjs from rendering-elements/shapes.ts. DO NOT EDIT.\n\npackage ru\n\n';
out += '// shapeDefs is shapesDefs of shapes.ts: the documented shapes.\nvar shapeDefs = []ShapeDef{\n';
for (const d of defs) {
  out += `\t{SemanticName: ${q(d.semanticName)}, Name: ${q(d.name)}, ShortName: ${q(d.shortName)}, Aliases: []string{${d.aliases.map(q).join(', ')}}, InternalAliases: []string{${d.internalAliases.map(q).join(', ')}}, Handler: ${q(d.handler)}},\n`;
}
out += '}\n\n// undocumentedShapes lists the shapes that have no documentation entry.\n// The name is both the shape id and the handler name.\nvar undocumentedShapes = []string{\n';
for (const u of undocumented) out += `\t${q(u)},\n`;
out += '}\n';
fs.writeFileSync('../../internal/ru/shapedefs_gen.go', out);
console.error('shape defs', defs.length, 'undocumented', undocumented.length, 'handlers', new Set(defs.map((d) => d.handler)).size);
