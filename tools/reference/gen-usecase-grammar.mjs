// Writes internal/diagrams/usecase/grammar_gen.go: the tables of the
// Chevrotain parser of the usecase diagram of mermaid 12.2.0.
//
// Chevrotain computes, for every OR, OPTION, MANY and AT_LEAST_ONE of a rule,
// the token sequences that select an alternative or enter the production
// (LL(k) lookahead with k = 3). The Go parser makes the same decisions from
// the same sequences, so they are taken from the real parser object:
//   - the token types in the order of the vocabulary, with the token types
//     that each category matches,
//   - the patterns of each lexer mode in the order in which the lexer tries
//     them, with the properties that the lexer derives for each pattern,
//   - for each decision of each rule, the lookahead paths that
//     getLookaheadPaths of chevrotain returns.
//
// Usage (in tools/reference): node gen-usecase-grammar.mjs
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EOF, getLookaheadPaths } from 'chevrotain';
import { usecase } from './usecase-lib.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '../../internal/diagrams/usecase/grammar_gen.go');

const { parser, lexer, tokens } = await usecase();
const maxLookahead = parser.maxLookahead;

// goName turns a token name into a Go identifier: LABEL_TEXT is tokLabelText.
const goName = (name) =>
  'tok' +
  name
    .toLowerCase()
    .split('_')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');

const vocabulary = [...tokens, EOF];
const byIdx = new Map(vocabulary.map((t) => [t.tokenTypeIdx, t]));

const kinds = {
  Alternation: 'prodOr',
  Option: 'prodOption',
  Repetition: 'prodMany',
  RepetitionMandatory: 'prodAtLeastOne',
};

// decisions lists the productions of a rule that need a lookahead, in the
// order of the grammar.
const decisions = (rule) => {
  const out = [];
  const walk = (prod) => {
    if (kinds[prod.constructor.name]) {
      out.push(prod);
    } else if (/WithSeparator$/.test(prod.constructor.name)) {
      throw new Error(`rule ${rule.name}: ${prod.constructor.name} is not supported by the Go parser`);
    }
    // A NonTerminal refers to another rule: its definition is not a part
    // of this rule.
    if (prod.constructor.name !== 'NonTerminal') {
      for (const child of prod.definition ?? []) {
        walk(child);
      }
    }
  };
  rule.definition.forEach(walk);
  return out;
};

const lines = [];
const emit = (s = '') => lines.push(s);

emit('// Code generated by tools/reference/gen-usecase-grammar.mjs. DO NOT EDIT.');
emit();
emit('// The tables of the Chevrotain parser of diagrams/usecase/parser of mermaid');
emit('// 12.2.0 (chevrotain 13.2.0): the token types of usecase.tokens.ts, and the');
emit('// lookahead paths that chevrotain computes for the grammar of');
emit('// usecase.parser.ts.');
emit();
emit('package usecase');
emit();
emit('// The token types, in the order of the vocabulary. tokEof is the EOF token');
emit('// type of chevrotain.');
emit('const (');
vocabulary.forEach((t, i) => emit(`\t${goName(t.name)}${i === 0 ? ' tokenType = iota' : ''}`));
emit('\tnumTokenTypes');
emit(')');
emit();
emit('// tokenTypeNames has the name of each token type.');
emit('var tokenTypeNames = [numTokenTypes]string{');
vocabulary.forEach((t) => emit(`\t${goName(t.name)}: ${JSON.stringify(t.name)},`));
emit('}');
emit();
emit('// categoryMatches has, for a token type that is a category, the token types');
emit('// that it matches (categoryMatches of chevrotain).');
emit('var categoryMatches = map[tokenType][]tokenType{');
for (const t of vocabulary) {
  if (t.categoryMatches.length > 0) {
    emit(`\t${goName(t.name)}: {${t.categoryMatches.map((idx) => goName(byIdx.get(idx).name)).join(', ')}},`);
  }
}
emit('}');
emit();
emit('// defaultLexerMode is the mode in which the lexer starts.');
emit(`const defaultLexerMode = ${JSON.stringify(lexer.defaultMode)}`);
emit();
emit('// lexerModes has the patterns of each lexer mode, in the order in which the');
emit('// lexer tries them (patternIdxToConfig of chevrotain). The comment of a');
emit('// pattern is its regular expression, or "custom" for a matcher function.');
emit('var lexerModes = map[string][]patternConfig{');
for (const mode of lexer.modes) {
  const configs = lexer.patternIdxToConfig[mode];
  emit(`\t${JSON.stringify(mode)}: {`);
  for (const config of configs) {
    const fields = [`typ: ${goName(config.tokenType.name)}`];
    if (config.group === undefined) {
      fields.push('skipped: true');
    } else if (config.group !== false) {
      throw new Error(`token ${config.tokenType.name}: the group ${config.group} is not supported by the Go lexer`);
    }
    if (config.canLineTerminator) {
      fields.push('canLineTerminator: true');
    }
    if (config.longerAlt !== undefined) {
      fields.push(`longerAlt: []tokenType{${config.longerAlt.map((i) => goName(configs[i].tokenType.name)).join(', ')}}`);
    }
    if (config.push !== undefined) {
      fields.push(`push: ${JSON.stringify(config.push)}`);
    }
    if (config.pop) {
      fields.push('pop: true');
    }
    const source = config.tokenType.PATTERN instanceof RegExp ? String(config.tokenType.PATTERN) : 'custom';
    emit(`\t\t{${fields.join(', ')}}, // ${source}`);
  }
  emit('\t},');
}
emit('}');
emit();
emit(`// maxLookahead is the maxLookahead of the parser.`);
emit(`const maxLookahead = ${maxLookahead}`);
emit();
emit('// ruleNames has the rules of the grammar in the order of their definition.');
emit('var ruleNames = []string{');
const gast = parser.getGAstProductions();
const rules = Object.values(gast);
for (const rule of rules) {
  emit(`\t${JSON.stringify(rule.name)},`);
}
emit('}');
emit();
emit('// lookaheadPaths has the lookahead paths of each decision of the grammar.');
emit('// For an OR there is one list of paths for each alternative. For an OPTION,');
emit('// a MANY and an AT_LEAST_ONE there is one list: the paths that enter the');
emit('// production.');
emit('var lookaheadPaths = map[decision][][][]tokenType{');
let count = 0;
for (const rule of rules) {
  for (const prod of decisions(rule)) {
    const prodType = prod.constructor.name;
    let alts = getLookaheadPaths({ occurrence: prod.idx, rule, prodType, maxLookahead: prod.maxLookahead || maxLookahead });
    if (prodType !== 'Alternation') {
      alts = [alts[0]];
    }
    emit(`\t{${JSON.stringify(rule.name)}, ${kinds[prodType]}, ${prod.idx}}: {`);
    for (const alt of alts) {
      emit(`\t\t{${alt.map((p) => '{' + p.map((t) => goName(t.name)).join(', ') + '}').join(', ')}},`);
    }
    emit('\t},');
    count++;
  }
}
emit('}');
emit();

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
execFileSync('gofmt', ['-w', outFile], { stdio: 'inherit' });
console.log(`${outFile}: ${vocabulary.length} token types, ${rules.length} rules, ${count} decisions`);
