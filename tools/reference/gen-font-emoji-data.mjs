#!/usr/bin/env node
// Writes internal/font/emoji_data_gen.go: the code points of the Unicode
// properties Emoji, Emoji_Presentation and Emoji_Modifier_Base, as sorted
// ranges. The values come from the Unicode data of this Node.js build (ICU),
// through the property escapes of regular expressions. Blink reads the same
// properties from ICU (Character::IsEmoji, IsEmojiEmojiDefault,
// IsEmojiModifierBase).
//
// Usage (in tools/reference): node gen-font-emoji-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, '../../internal/font/emoji_data_gen.go');

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

const tables = [
  ['emojiRanges', 'Emoji', /\p{Emoji}/u],
  ['emojiPresentationRanges', 'Emoji_Presentation', /\p{Emoji_Presentation}/u],
  ['emojiModifierBaseRanges', 'Emoji_Modifier_Base', /\p{Emoji_Modifier_Base}/u],
];
const hex = (v) => '0x' + v.toString(16);
let src = `// Code generated by tools/reference/gen-font-emoji-data.mjs from the Unicode data of Node.js ${process.version} (Unicode ${process.versions.unicode}, ICU ${process.versions.icu}). DO NOT EDIT.

package font
`;
for (const [name, property, re] of tables) {
  const list = ranges(re);
  const count = list.reduce((n, [a, b]) => n + b - a + 1, 0);
  src += `\n// ${name} holds the ${count} code points of the Unicode property ${property}\n// as sorted ranges: first, last, first, last.\nvar ${name} = [...]rune{`;
  list.forEach(([a, b], i) => {
    src += (i % 6 === 0 ? '\n\t' : ' ') + `${hex(a)}, ${hex(b)},`;
  });
  src += '\n}\n';
}
fs.writeFileSync(outFile, src);
console.log(`${path.relative(path.join(here, '../..'), outFile)}: ${tables.map(([n, , re]) => `${n} ${ranges(re).length} ranges`).join(', ')}`);
